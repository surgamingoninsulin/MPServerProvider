using System.Text.Json;
using MPServerProvider.Core.Models;

namespace MPServerProvider.Core.Providers;

public sealed class BeamMpProvider : IInstallProvider
{
    private const string ReleasesApi = "https://api.github.com/repos/BeamMP/BeamMP-Server/releases/latest";

    public string Id => "beammp";

    public Task<List<string>> GetVersionsAsync(GameDefinition game, string? variant, CancellationToken ct)
        => Task.FromResult(new List<string> { "latest" });

    public async Task<InstallResult> InstallAsync(InstallRequest request, IProgress<InstallProgress> progress, CancellationToken ct)
    {
        progress.Report(InstallProgress.Indeterminate("Resolving BeamMP-Server release…"));

        var body = await DownloadHelper.GetStringAsync(ReleasesApi, ct).ConfigureAwait(false);
        using var doc = JsonDocument.Parse(body);
        var tag = doc.RootElement.TryGetProperty("tag_name", out var tagEl) ? tagEl.GetString() ?? string.Empty : string.Empty;

        string? downloadUrl = null;
        string? sha256 = null;
        if (doc.RootElement.TryGetProperty("assets", out var assets) && assets.ValueKind == JsonValueKind.Array)
        {
            foreach (var asset in assets.EnumerateArray())
            {
                if (asset.TryGetProperty("name", out var nameEl) && nameEl.GetString() == "BeamMP-Server.exe")
                {
                    downloadUrl = asset.TryGetProperty("browser_download_url", out var urlEl) ? urlEl.GetString() : null;
                    // GitHub publishes "digest": "sha256:<hex>" for release assets; verify when present.
                    if (asset.TryGetProperty("digest", out var digestEl) && digestEl.ValueKind == JsonValueKind.String
                        && digestEl.GetString() is { } digest && digest.StartsWith("sha256:", StringComparison.OrdinalIgnoreCase))
                    {
                        sha256 = digest["sha256:".Length..];
                    }

                    break;
                }
            }
        }

        if (downloadUrl is null)
        {
            throw new InvalidOperationException("No Windows executable found in the latest BeamMP-Server release.");
        }

        var exePath = Path.Combine(request.TargetDir, "BeamMP-Server.exe");

        progress.Report(InstallProgress.Indeterminate($"Downloading BeamMP-Server {tag}"));
        await DownloadHelper.DownloadFileAsync(downloadUrl, exePath, ct, expectedSha256: sha256).ConfigureAwait(false);

        Directory.CreateDirectory(Path.Combine(request.TargetDir, "Resources", "Client"));
        Directory.CreateDirectory(Path.Combine(request.TargetDir, "Resources", "Server"));

        WriteConfig(request);

        return new InstallResult
        {
            ServerFile = "BeamMP-Server.exe",
            Version = tag,
            StartCommand = null,
            JavaMajor = 0,
        };
    }

    internal static void WriteConfig(InstallRequest request)
    {
        var path = Path.Combine(request.TargetDir, "ServerConfig.toml");
        if (File.Exists(path))
        {
            return;
        }

        var contents =
            "# Generated by MPServerProvider (BeamMP-Server format)\n" +
            "[General]\n" +
            $"Name = \"{ConfigText.TomlString(request.ServerName)}\"\n" +
            $"Port = {request.Port}\n" +
            "MaxCars = 1\n" +
            "MaxPlayers = 8\n" +
            "Map = \"/levels/gridmap_v2/info.json\"\n" +
            $"Description = \"{ConfigText.TomlString(request.Description)}\"\n" +
            "# REQUIRED: paste your free AuthKey from https://keymaster.beammp.com\n" +
            "AuthKey = \"\"\n" +
            "Private = true";

        File.WriteAllText(path, contents);
    }
}
